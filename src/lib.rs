    m.add_class::<xml::Xml>()?;
    m.add_class::<package::Package>()?;
    m.add_class::<package::Part>()?;
    m.add_class::<text::Story>()?;
    m.add_class::<text::Range>()?;
    m.add_class::<definitions::Style>()?;
    m.add_class::<definitions::Level>()?;
    m.add_class::<definitions::NumberingInstance>()?;
    m.add_class::<tables::Table>()?;
    m.add_class::<comments::Comments>()?;
